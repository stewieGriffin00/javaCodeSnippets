class Main{
    public static void main(String[] args){
        long num1= 76_576_576L;
        // if the number assigned to the long reference is larger than the 'int' range only then 
        // we need to write a 'l' after the number. Otherwise for  the numbers lesser than 
        // 'int' range writing 'l' in the end is optional. 
        long num2 = 98_757_658_987_675L; 
        System.out.println(num1);  
        System.out.println(num2);  
    }   
}
