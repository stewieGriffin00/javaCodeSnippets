import java.util.Arrays;
class Database{
    public static void main(String[] args){
        int[][] arr1 = {{1,2}, {3,4}}; 
        
        System.out.println(" Two Dimensional array ");
        for(int i=0; i<arr1.length; i++){
            for(int j= 0; j<arr1.length; j++){
                System.out.print(arr1[i][j]+" ");
            }
            System.out.println();
        }
        System.out.println();
    }
}
